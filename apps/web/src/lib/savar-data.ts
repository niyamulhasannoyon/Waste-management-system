export function resolveNearestWardLocal(lat: number, lng: number): WardSummary {
  let closest = SAVAR_WARDS_SEED[0]!;
  let minDist = Number.POSITIVE_INFINITY;

  for (const ward of SAVAR_WARDS_SEED) {
    const dLat = ward.centroid_lat - lat;
    const dLng = ward.centroid_lng - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDist) {
      minDist = distSq;
      closest = ward;
    }
  }
  return closest;
}
